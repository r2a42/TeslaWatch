#!/usr/bin/env python3
"""Writes Tests/TeslaKitTests/GoldenVectors.swift from tools/vectors.txt."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
vectors = dict(line.split(" ", 1) for line in (root / "tools/vectors.txt").read_text().splitlines())
out = ["// Generated by tools/gen_tests.py from tools/reference_vectors.py. Do not edit.", "",
       "enum Golden {"]
for name, value in vectors.items():
    swift_name = "".join(p.capitalize() if i else p.lower() for i, p in enumerate(name.split("_")))
    out.append(f'    static let {swift_name} = "{value}"')
out.append("}")
(root / "Tests/TeslaKitTests/GoldenVectors.swift").write_text("\n".join(out) + "\n")
print("\n".join(l[:90] for l in out))
